export function textWidth(text: string, scale = 1): number {
  return text.length * 6 * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    const g = FONT[ch] ?? FONT[ch.toLowerCase()] ?? FONT[ch.toUpperCase()];
    if (g) {
      for (let i = 0; i < 35; i++) {
        if (g[i] === "1") {
          ctx.fillRect(cx + (i % 5) * scale, y + Math.floor(i / 5) * scale, scale, scale);
        }
      }
    }
    cx += 6 * scale;
  }
}

export function wrapText(text: string, maxChars: number): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = "";
  for (const word of words) {
    const next = cur ? `${cur} ${word}` : word;
    if (next.length > maxChars && cur) {
      lines.push(cur);
      cur = word.length > maxChars ? word.slice(0, maxChars) : word;
    } else {
      cur = next.length > maxChars ? next.slice(0, maxChars) : next;
    }
  }
  if (cur) lines.push(cur);
  return lines.length ? lines : [""];
}

export function ascii(text: string): string {
  return text
    .replace(/[’‘]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[—–]/g, "-")
    .replace(/…/g, "...");
}
