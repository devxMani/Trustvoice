function glyph(rows: string[]): string {
  if (rows.length !== 7) throw new Error(`glyph rows ${rows.length}`);
  for (const row of rows) {
    if (row.length !== 5) throw new Error(`glyph width "${row}"`);
  }
  return rows.join("").replaceAll("#", "1").replaceAll(".", "0");
}

